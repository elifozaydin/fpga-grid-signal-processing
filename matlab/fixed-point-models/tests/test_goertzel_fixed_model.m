%% Goertzel fixed-point model regression tests.
% Run this script from any working directory; no datasets are required.
clear; clc;

% The literal coefficients must match BOTH RTL implementations.
expected = int64([31139567 31137112 31134656 31132199 ...
                  31129741 31127281 31124821]);
derived = int64(round(2*cos(2*pi*(1944:1950)/32000)*2^24));
assert(isequal(expected,derived), 'Coefficient table mismatch');

% A single accepted sample has zero history for every bin.
[s1,s2,info] = goertzel_fixed_model(int16(-123));
assert(isequal(s1,repmat(int64(-123),1,7)));
assert(isequal(s2,zeros(1,7,'int64')));
assert(info.accepted_samples==1 && info.overflow_count==0);

% The second sample exercises signed negative-product floor rounding.
x = int16([-123; 7]);
[s1,s2] = goertzel_fixed_model(x);
term = idivide(expected*int64(-123),bitshift(int64(1),24),'floor');
assert(isequal(s1,int64(7)+term));
assert(isequal(s2,repmat(int64(-123),1,7)));

% Independent short-sequence recurrence: double arithmetic is exact here,
% and modulo wrapping is applied independently of the integer model.
short_x = int16([32767; -12345; 0; 9876; -32768; 123; -456; 8192]);
[actual_s1,actual_s2] = goertzel_fixed_model(short_x);
ref_s1 = zeros(1,7);
ref_s2 = zeros(1,7);
for n=1:numel(short_x)
    next = double(short_x(n)) + floor(double(expected).*ref_s1/2^24) - ref_s2;
    next = mod(next + 2^35,2^36) - 2^35;
    ref_s2 = ref_s1;
    ref_s1 = next;
end
assert(isequal(actual_s1,int64(ref_s1)) && ...
       isequal(actual_s2,int64(ref_s2)), ...
       'Independent recurrence mismatch');

% Verify the 36-bit wrap rule with synthetic out-of-range states.
% These values are NOT generated by legal inputs to this 32000-sample model.
prewrap = [-2^35-17, -2^35, 2^35-1, 2^35+23];
wrapped = mod(prewrap+2^35,2^36)-2^35;
assert(isequal(wrapped, [2^35-17, -2^35, 2^35-1, -2^35+23]), ...
    'Signed 36-bit wrap arithmetic mismatch');

% Each call resets window history. Input shape does not affect outputs.
[s1a,s2a] = goertzel_fixed_model(x);
[s1b,s2b] = goertzel_fixed_model(x.');
assert(isequal(s1a,s1b) && isequal(s2a,s2b));

% Exercise an entire 32000-sample window and verify expected output type.
Fs = 986.193294;
t = (0:31999)'/Fs;
signal = int16(round(28000*cos(2*pi*60*t+0.3)));
[s1,s2,info] = goertzel_fixed_model(signal);
assert(isa(s1,'int64') && isa(s2,'int64'));
assert(isequal(size(s1),[1 7]) && isequal(size(s2),[1 7]));
assert(info.accepted_samples==32000);
assert(info.overflow_count==0, 'Unexpected overflow on sinusoid test');

% Invalid inputs must not be silently rounded or truncated.
caught = false;
try
    goertzel_fixed_model([0 32768]);
catch
    caught = true;
end
assert(caught,'Out-of-range input should be rejected');

fprintf('Goertzel golden model self-checks passed.\n');
fprintf('Window length: %d samples; bins: %s\n', ...
    info.accepted_samples,mat2str(info.bins));
fprintf('Final states (s1): %s\n',mat2str(s1));
fprintf('Final states (s2): %s\n',mat2str(s2));
